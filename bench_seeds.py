"""Multi-seed statistical validation for SHD v3.7.

Design (honest and cheap):
- Train/test split is FIXED (random_state=42, same as the published single-seed
  numbers). The Oracle baseline therefore does not depend on the seed and is
  fitted once.
- Only the coreset-construction randomness varies per seed: the SHD projector
  and lattice seed, the Random selection, and the K-Means seed.
- For each seed we record KRR and GBM metrics (all + rare regime), then run
  paired Wilcoxon signed-rank tests: SHD vs Random, SHD vs K-Means.

Results are dumped to bench_seeds_results.json — the single source of truth.
Progress is checkpointed after every seed, so an interrupted long run keeps the
seeds it already finished (`partial: true` marks an incomplete dataset).

Baselines: Random, MiniBatch K-Means, Kernel Thinning (Dwivedi & Mackey, JMLR 2024)
and Supervised Kernel Thinning (Gong et al., NeurIPS 2024) — the latter two run
through `kt_baseline.py`, a pure-numpy port verified bit-exact against the
official Microsoft `goodpoints` X-path (`verify_kt_port.py`).

Usage:
    python bench_seeds.py [--seeds 20] [--dataset superconduct|reactor|both] [--skip-kt]
"""

from __future__ import annotations

import argparse
import json
import os
import time

import numpy as np
from scipy.spatial.distance import cdist
from scipy.stats import wilcoxon
from sklearn.cluster import MiniBatchKMeans
from sklearn.ensemble import HistGradientBoostingRegressor
from sklearn.kernel_ridge import KernelRidge
from sklearn.metrics import mean_squared_error, r2_score
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

from kt_baseline import kt_skt_joint, kt_thin, median_bandwidth_sq
from shd import SpectralHologramDistiller


# --- datasets ----------------------------------------------------------------


def load_reactor(n=20000, seed=42):
    """Synthetic 4D stream with a rare phase-transition regime (hot band)."""
    rng = np.random.default_rng(seed)
    X = rng.normal(0.0, 1.0, size=(n, 4))
    y = np.sin(2.0 * X[:, 0]) + 0.5 * X[:, 1] * X[:, 2] + 0.1 * rng.normal(size=n)
    hot = np.abs(X[:, 0]) > 1.8
    y[hot] += 6.0 + 1.5 * X[hot, 3]
    crit_threshold = float(np.percentile(y, 97.0))  # rare-regime cut on y
    return X, y, crit_threshold, "Reactor 4D (phase transition)"


def load_superconduct():
    """UCI Superconductivity (21,263 x 81). Falls back to California housing."""
    from sklearn.datasets import fetch_california_housing, fetch_openml

    try:
        try:
            ds = fetch_openml(name="superconduct", version=1, as_frame=False, parser="auto")
        except ImportError:
            # parser='auto' needs pandas for dense data; liac-arff does not.
            ds = fetch_openml(name="superconduct", version=1, as_frame=False, parser="liac-arff")
        X = np.asarray(ds.data, dtype=np.float64)
        y = np.asarray(ds.target, dtype=np.float64)
        if X.shape[1] == 81 and len(X) > 20000:
            return X, y, 77.0, "UCI Superconductivity"
    except Exception as e:  # pragma: no cover - network dependent
        print(f"[warn] OpenML fetch failed ({e}); falling back to California housing")
    ds = fetch_california_housing()
    X = np.asarray(ds.data, dtype=np.float64)
    y = np.asarray(ds.target, dtype=np.float64)
    return X, y, float(np.percentile(y, 97.0)), "California housing (fallback)"


# --- coreset builders ---------------------------------------------------------


def build_shd(X_tr, y_tr, seed, m, batch, crit_threshold):
    d = SpectralHologramDistiller(
        crystal_size=m, high_band_ratio=0.26, sketch_dim=256,
        tail_quantile=84.0, phase_kappa=3.2, random_state=seed,
    )
    for i in range(0, len(X_tr), batch):
        d.partial_fit(X_tr[i : i + batch], y_tr[i : i + batch])
    d.finalize_crystal()
    n_rare = int(np.sum(d.crystal_Y >= crit_threshold))
    return d.crystal_X, np.asarray(d.crystal_Y, dtype=np.float64), d.gamma_weights, n_rare


def build_random(X_tr, y_tr, seed, m):
    rng = np.random.default_rng(seed)
    idx = rng.choice(len(X_tr), size=m, replace=False)
    return X_tr[idx], y_tr[idx], None


def build_kmeans(X_tr, y_tr, Z_tr, seed, m):
    """MiniBatchKMeans medoid coreset with EXACTLY m unique training rows.

    DISCLOSURE (hunt finding #6, docs/hunt_report_shd_v3.11.md): the committed
    `bench_seeds_results.json` was generated by the OLD extraction -- a bare
    per-center `argmin(cdist(centers, Z))` -- which returns the SAME row for
    every center that shares a nearest point. On superconductivity the K-Means
    arm received only 265 UNIQUE rows out of m=300 (35 duplicates), so the
    "equal budget M=300" comparisons in README §1 carry this confound (SHD got
    300 unique points, K-Means effectively fewer). This fix does NOT modify
    the committed JSON; its numbers will be regenerated at the next full run.

    New deterministic scheme (same seed => same coreset; consumes NO RNG, so
    the random streams of the other arms are untouched):
      1) each cluster takes its argmin medoid (same distance rule as before);
      2) duplicates are dropped preserving cluster order -- the first cluster
         to claim a row keeps it;
      3) every cluster left without a unique medoid takes the closest
         not-yet-selected row to ITS OWN center (starved clusters in ascending
         order, while the selected count is below m);
      4) safety net for degenerate pools: remaining clusters are filled with
         the globally closest unselected (center, row) pairs.
    Row i of the coreset always represents cluster i, so the per-cluster
    weights `w` stay positionally aligned; when all medoids are distinct the
    output is identical to the old code. This single builder serves BOTH
    datasets routed through run_dataset() (superconduct AND reactor) and every
    other bench_* module that imports build_kmeans from here.
    """
    km = MiniBatchKMeans(n_clusters=m, batch_size=2048, random_state=seed, n_init=3).fit(Z_tr)
    counts = np.bincount(km.labels_, minlength=m).astype(np.float64) + 1.0
    w = counts / np.mean(counts)
    D = cdist(km.cluster_centers_, Z_tr, metric="sqeuclidean")  # (m, n): center -> row sq. dist
    n_pts = D.shape[1]
    medoid = np.argmin(D, axis=1)               # step 1: same rule as the old bare argmin
    sel = np.full(m, -1, dtype=np.intp)         # cluster -> selected row index
    taken = np.zeros(n_pts, dtype=bool)         # rows already in the coreset
    starved = []
    for c in range(m):                          # step 2: first cluster wins a shared medoid
        p = int(medoid[c])
        if taken[p]:
            starved.append(c)
        else:
            taken[p] = True
            sel[c] = p
    for c in starved:                           # step 3: own-center deterministic top-up
        if not np.any(~taken):
            break
        p = int(np.argmin(np.where(taken, np.inf, D[c])))
        taken[p] = True
        sel[c] = p
    while np.any(sel < 0) and np.any(~taken):   # step 4: global safety net (degenerate pools)
        Dm = np.where(taken[None, :] | (sel >= 0)[:, None], np.inf, D)
        c, p = np.unravel_index(int(np.argmin(Dm)), Dm.shape)
        taken[p] = True
        sel[c] = int(p)
    assigned = np.nonzero(sel >= 0)[0]          # < m only if n_pts < m (infeasible budget)
    idx = sel[assigned]
    return X_tr[idx], y_tr[idx], w[assigned]


def _kt_subsample_and_halvings(n_total, target_m):
    """Find the largest halving count h in {4,3,2,1} where target_m * 2^h <= n_total.

    For m=300 and n=16k-17k: h=4, n_sub=4800, so kt_thin(..., m=4) returns
    exactly 4800 // 16 = 300 points, perfectly matching the crystal budget.
    """
    for h in (4, 3, 2, 1):
        if target_m * (2 ** h) <= n_total:
            return target_m * (2 ** h), h
    return n_total, 0


def build_kt(X_tr, y_tr, Z_tr, seed, m):
    """Unsupervised Kernel Thinning (Dwivedi & Mackey, JMLR 2024).

    Compresses an i.i.d. subsample of size m*2^h down to m points using
    a Gaussian kernel on standard-scaled features Z_tr with median-heuristic
    bandwidth. Coreset is unweighted empirical.
    """
    rng = np.random.default_rng(seed)
    n_sub, h = _kt_subsample_and_halvings(len(X_tr), m)
    sub_idx = rng.choice(len(X_tr), size=n_sub, replace=False)
    Z_sub = Z_tr[sub_idx]
    var = median_bandwidth_sq(Z_sub, seed=seed)
    thin_idx = kt_thin(Z_sub, h, var, seed=seed)
    final_idx = sub_idx[thin_idx]
    return X_tr[final_idx], y_tr[final_idx], None


def build_skt(X_tr, y_tr, Z_tr, seed, m):
    """Supervised Kernel Thinning (Gong, Choi & Dwivedi, NeurIPS 2024).

    Runs KT on the product kernel k_X(z, z') * k_Y(y, y'), equivalently a
    Gaussian kernel on joint vectors [Z, sqrt(var_X / var_Y) * y_std].
    """
    rng = np.random.default_rng(seed)
    n_sub, h = _kt_subsample_and_halvings(len(X_tr), m)
    sub_idx = rng.choice(len(X_tr), size=n_sub, replace=False)
    Z_sub = Z_tr[sub_idx]
    y_sub = y_tr[sub_idx]
    y_scaled = (y_sub - float(np.mean(y_sub))) / (float(np.std(y_sub)) + 1e-12)
    var_x = median_bandwidth_sq(Z_sub, seed=seed)
    var_y = median_bandwidth_sq(y_scaled, seed=seed)
    W_sub, var_w = kt_skt_joint(Z_sub, y_scaled, var_x, var_y)
    thin_idx = kt_thin(W_sub, h, var_w, seed=seed)
    final_idx = sub_idx[thin_idx]
    return X_tr[final_idx], y_tr[final_idx], None


# --- model evaluation ----------------------------------------------------------


def eval_models(X_c, y_c, w_c, scaler, model_seed, X_te, Z_te, y_te, X_te_crit, Z_te_crit, y_te_crit, rbf_gamma):
    Z_c = scaler.transform(X_c)
    krr = KernelRidge(kernel="rbf", alpha=0.08, gamma=rbf_gamma)
    krr.fit(Z_c, y_c, sample_weight=w_c)
    pred_all = krr.predict(Z_te)
    pred_crit = krr.predict(Z_te_crit)
    krr_row = (
        float(np.sqrt(mean_squared_error(y_te, pred_all))),
        float(np.sqrt(mean_squared_error(y_te_crit, pred_crit))),
        float(r2_score(y_te, pred_all)),
    )

    gbm = HistGradientBoostingRegressor(
        max_iter=120, max_leaf_nodes=20, min_samples_leaf=5, random_state=model_seed
    )
    gbm.fit(X_c, y_c, sample_weight=w_c)
    g_all = gbm.predict(X_te)
    g_crit = gbm.predict(X_te_crit)
    gbm_row = (
        float(np.sqrt(mean_squared_error(y_te, g_all))),
        float(np.sqrt(mean_squared_error(y_te_crit, g_crit))),
        float(r2_score(y_te, g_all)),
    )
    return {
        "krr_rmse_all": krr_row[0], "krr_rmse_crit": krr_row[1], "krr_r2": krr_row[2],
        "gbm_rmse_all": gbm_row[0], "gbm_rmse_crit": gbm_row[1], "gbm_r2": gbm_row[2],
    }


# --- per-dataset experiment -----------------------------------------------------


def _checkpoint(path, key, records, m, seeds, oracle, title, t0, done):
    """Write progress after each seed so an interrupted long run is not lost."""
    if not path:
        return
    payload = {
        "results": {
            key: {
                "dataset": key,
                "title": title,
                "crystal_size": m,
                "n_seeds": len(seeds),
                "seeds": list(seeds),
                "split_random_state": 42,
                "oracle": {
                    "krr_rmse_all": oracle["krr"][0], "krr_rmse_crit": oracle["krr"][1],
                    "krr_r2": oracle["krr"][2], "gbm_rmse_all": oracle["gbm"][0],
                    "gbm_rmse_crit": oracle["gbm"][1], "gbm_r2": oracle["gbm"][2],
                },
                "records": records,
                "wilcoxon": {},
                "elapsed_sec": time.perf_counter() - t0,
                "partial": not done,
            }
        }
    }
    merged = {"config": {}, "results": {}}
    try:
        with open(path, encoding="utf-8") as f:
            existing = json.load(f)
        if isinstance(existing.get("results"), dict):
            merged = existing
    except (FileNotFoundError, json.JSONDecodeError):
        pass
    merged.setdefault("results", {})
    merged["results"].update(payload["results"])
    tmp = path + ".part"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(merged, f, ensure_ascii=False, indent=1)
    os.replace(tmp, path)


def run_dataset(key, seeds, m, batch, model_seed, include_kt=True, checkpoint_path=None):
    t0 = time.perf_counter()
    if key == "superconduct":
        X_raw, y_raw, crit_threshold, title = load_superconduct()
        if X_raw.shape[1] != 81:
            raise RuntimeError(
                "UCI Superconductivity fetch failed (California-housing fallback); "
                "aborting so the fallback cannot overwrite the headline artifact "
                "(same guard as bench_gaps.py / bench_frontier.py)")
    else:
        X_raw, y_raw, crit_threshold, title = load_reactor()

    X_tr, X_te, y_tr, y_te = train_test_split(X_raw, y_raw, test_size=0.20, random_state=42)
    is_crit = y_te >= crit_threshold
    X_te_crit, y_te_crit = X_te[is_crit], y_te[is_crit]

    scaler = StandardScaler().fit(X_tr)
    Z_tr = scaler.transform(X_tr)
    Z_te = scaler.transform(X_te)
    Z_te_crit = scaler.transform(X_te_crit)

    d_feat = X_raw.shape[1]
    rbf_gamma = 1.0 / (d_feat * 1.1)

    # Oracle: seed-independent, fit once.
    # NOTE: the KRR oracle uses the first `n_oracle` rows in split order. Both
    # datasets routed through run_dataset() are split with shuffle=True, so this
    # is an unbiased random subsample and reproduces the published oracle table.
    # Do NOT switch to a fresh random draw without also regenerating the
    # committed `bench_seeds_results.json` and the README oracle rows.
    # For a TIME-ORDERED stream this slice would train on the earliest period
    # only -- pass an explicit subsample instead of reusing run_dataset().
    oracle = {"krr": None, "gbm": None}
    n_oracle = min(9000, len(X_tr))
    krr = KernelRidge(kernel="rbf", alpha=0.08, gamma=rbf_gamma)
    krr.fit(scaler.transform(X_tr[:n_oracle]), y_tr[:n_oracle])
    oracle["krr"] = (
        float(np.sqrt(mean_squared_error(y_te, krr.predict(Z_te)))),
        float(np.sqrt(mean_squared_error(y_te_crit, krr.predict(Z_te_crit)))),
        float(r2_score(y_te, krr.predict(Z_te))),
    )
    gbm = HistGradientBoostingRegressor(
        max_iter=120, max_leaf_nodes=20, min_samples_leaf=5, random_state=model_seed
    )
    gbm.fit(X_tr, y_tr)
    oracle["gbm"] = (
        float(np.sqrt(mean_squared_error(y_te, gbm.predict(X_te)))),
        float(np.sqrt(mean_squared_error(y_te_crit, gbm.predict(X_te_crit)))),
        float(r2_score(y_te, gbm.predict(X_te))),
    )
    print(f"[{key}] {title}: n_train={len(X_tr):,}, test_crit={len(X_te_crit):,}, oracle done "
          f"({time.perf_counter() - t0:.1f}s)")

    records = []
    for seed in seeds:
        t_s = time.perf_counter()
        rec = {"seed": seed}

        Xc, yc, wc, n_rare = build_shd(X_tr, y_tr, seed, m, batch, crit_threshold)
        rec["shd"] = eval_models(Xc, yc, wc, scaler, model_seed,
                                 X_te, Z_te, y_te, X_te_crit, Z_te_crit, y_te_crit, rbf_gamma)
        rec["shd"]["rare_captured"] = n_rare

        Xc, yc, wc = build_random(X_tr, y_tr, seed, m)
        rec["random"] = eval_models(Xc, yc, wc, scaler, model_seed,
                                    X_te, Z_te, y_te, X_te_crit, Z_te_crit, y_te_crit, rbf_gamma)
        rec["random"]["rare_captured"] = int(np.sum(yc >= crit_threshold))

        Xc, yc, wc = build_kmeans(X_tr, y_tr, Z_tr, seed, m)
        rec["kmeans"] = eval_models(Xc, yc, wc, scaler, model_seed,
                                    X_te, Z_te, y_te, X_te_crit, Z_te_crit, y_te_crit, rbf_gamma)
        rec["kmeans"]["rare_captured"] = int(np.sum(yc >= crit_threshold))

        if include_kt:
            Xc, yc, wc = build_kt(X_tr, y_tr, Z_tr, seed, m)
            rec["kt"] = eval_models(Xc, yc, wc, scaler, model_seed,
                                    X_te, Z_te, y_te, X_te_crit, Z_te_crit, y_te_crit, rbf_gamma)
            rec["kt"]["rare_captured"] = int(np.sum(yc >= crit_threshold))

            Xc, yc, wc = build_skt(X_tr, y_tr, Z_tr, seed, m)
            rec["skt"] = eval_models(Xc, yc, wc, scaler, model_seed,
                                     X_te, Z_te, y_te, X_te_crit, Z_te_crit, y_te_crit, rbf_gamma)
            rec["skt"]["rare_captured"] = int(np.sum(yc >= crit_threshold))

        records.append(rec)
        _checkpoint(checkpoint_path, key, records, m, seeds, oracle, title, t0, done=False)
        kt_s = f" kt={rec['kt']['krr_rmse_crit']:.2f} skt={rec['skt']['krr_rmse_crit']:.2f}" if include_kt else ""
        print(f"[{key}] seed {seed:2d}: shd krr_crit={rec['shd']['krr_rmse_crit']:.2f} "
              f"rand={rec['random']['krr_rmse_crit']:.2f} km={rec['kmeans']['krr_rmse_crit']:.2f}{kt_s} "
              f"rare={n_rare} ({time.perf_counter() - t_s:.1f}s)", flush=True)

    # Paired Wilcoxon tests.
    tests = {}
    pairs = [p for p in ["random", "kmeans", "kt", "skt"] if p in records[0]]
    for metric in ["krr_rmse_all", "krr_rmse_crit", "krr_r2", "gbm_rmse_all", "gbm_rmse_crit", "gbm_r2"]:
        higher_is_better = metric.endswith("_r2")
        for pair in pairs:
            a = np.array([r["shd"][metric] for r in records])
            b = np.array([r[pair][metric] for r in records])
            diff = a - b
            if np.allclose(diff, 0):
                stat, p = 0.0, 1.0
            else:
                stat, p = wilcoxon(a, b)
            wins = int(np.sum(diff > 0)) if higher_is_better else int(np.sum(diff < 0))
            tests[f"shd_vs_{pair}_{metric}"] = {
                "median_shd": float(np.median(a)),
                "iqr_shd": float(np.percentile(a, 75) - np.percentile(a, 25)),
                "median_" + pair: float(np.median(b)),
                "iqr_" + pair: float(np.percentile(b, 75) - np.percentile(b, 25)),
                "wins_shd": wins,
                "statistic": float(stat),
                "p_value": float(p),
            }

    _checkpoint(checkpoint_path, key, records, m, seeds, oracle, title, t0, done=True)

    summary = {
        "dataset": key,
        "title": title,
        "crystal_size": m,
        # Provenance: `batch` changes how partial_fit chunks the stream, which
        # changes the crystal, so it must be recorded with the records rather
        # than inferred. `model_seed` lives here too because results merged from
        # runs with different model seeds would otherwise be indistinguishable.
        "batch": int(batch),
        "model_seed": int(model_seed),
        "n_seeds": len(seeds),
        "seeds": list(seeds),
        "split_random_state": 42,
        "oracle": {"krr_rmse_all": oracle["krr"][0], "krr_rmse_crit": oracle["krr"][1],
                   "krr_r2": oracle["krr"][2], "gbm_rmse_all": oracle["gbm"][0],
                   "gbm_rmse_crit": oracle["gbm"][1], "gbm_r2": oracle["gbm"][2]},
        "records": records,
        "wilcoxon": tests,
        "elapsed_sec": time.perf_counter() - t0,
    }
    print(f"[{key}] done in {summary['elapsed_sec']:.1f}s")
    return summary


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=20)
    ap.add_argument("--dataset", choices=["superconduct", "reactor", "both", "summary"], default="both")
    ap.add_argument("--model-seed", type=int, default=42)
    ap.add_argument("--skip-kt", action="store_true", help="Skip the slower KT and SKT arms")
    ap.add_argument("--output", default="bench_seeds_results.json", help="Output JSON path")
    args = ap.parse_args()

    seeds = list(range(args.seeds))
    path = args.output
    out = {"config": {"n_seeds": args.seeds, "model_seed": args.model_seed}, "results": {}}
    try:
        with open(path, "r", encoding="utf-8") as f:
            prev = json.load(f)
            if isinstance(prev.get("results"), dict):
                out["results"].update(prev["results"])
    except FileNotFoundError:
        pass
    if args.dataset == "summary":
        keys = list(out["results"].keys())
    else:
        keys = ["superconduct", "reactor"] if args.dataset == "both" else [args.dataset]
        for key in keys:
            out["results"][key] = run_dataset(
                key, seeds, m=300, batch=2500, model_seed=args.model_seed,
                include_kt=not args.skip_kt, checkpoint_path=path,
            )

    # Recompute Wilcoxon + IQR across all stored datasets to guarantee schema uniformity.
    for key, res in out["results"].items():
        records = res["records"]
        pairs = [p for p in ["random", "kmeans", "kt", "skt"] if p in records[0]]
        tests = {}
        for metric in ["krr_rmse_all", "krr_rmse_crit", "krr_r2", "gbm_rmse_all", "gbm_rmse_crit", "gbm_r2"]:
            higher_is_better = metric.endswith("_r2")
            for pair in pairs:
                a = np.array([r["shd"][metric] for r in records])
                b = np.array([r[pair][metric] for r in records])
                diff = a - b
                stat, p = (0.0, 1.0) if np.allclose(diff, 0) else wilcoxon(a, b)
                wins = int(np.sum(diff > 0)) if higher_is_better else int(np.sum(diff < 0))
                tests[f"shd_vs_{pair}_{metric}"] = {
                    "median_shd": float(np.median(a)),
                    "iqr_shd": float(np.percentile(a, 75) - np.percentile(a, 25)),
                    "median_" + pair: float(np.median(b)),
                    "iqr_" + pair: float(np.percentile(b, 75) - np.percentile(b, 25)),
                    "wins_shd": wins,
                    "statistic": float(stat),
                    "p_value": float(p),
                }
        res["wilcoxon"] = tests

    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    print(f"\nSaved -> {path}")

    # Compact summary.
    for key in out["results"]:
        r = out["results"][key]
        rares = [rec["shd"]["rare_captured"] for rec in r["records"]]
        print(f"\n=== {key}: {r['title']} (n_seeds={r['n_seeds']}) ===")
        print(f"Oracle KRR: all={r['oracle']['krr_rmse_all']:.2f} crit={r['oracle']['krr_rmse_crit']:.2f} r2={r['oracle']['krr_r2']:.4f}")
        print(f"Oracle GBM: all={r['oracle']['gbm_rmse_all']:.2f} crit={r['oracle']['gbm_rmse_crit']:.2f} r2={r['oracle']['gbm_r2']:.4f}")
